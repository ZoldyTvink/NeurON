def compact_context(context):
    """Remove transport identifiers and repeated fields, retaining clinical values verbatim."""

    def pick(row, keys):
        return {key: row[key] for key in keys if key in row}

    result = {
        key: context[key]
        for key in ("pharmacy", "limits", "timezone", "tool_results", "tools_complete")
        if key in context
    }
    result["plans"] = []
    for plan in context.get("plans", []):
        row = pick(
            plan,
            ("id", "title", "doctor_name", "notes", "scheduled", "purchase_status"),
        )
        row["items"] = [
            pick(
                item,
                (
                    "name",
                    "form",
                    "strength",
                    "dosage",
                    "start_date",
                    "end_date",
                    "times",
                    "weekdays",
                    "timezone",
                    "notes",
                ),
            )
            for item in plan.get("items", [])
        ]
        result["plans"].append(row)
    result["calendar_events"] = [
        pick(event, ("title", "scheduled_at", "dosage", "status", "source"))
        for event in context.get("calendar_events", [])
    ]
    result["appointments"] = [
        pick(item, ("doctor", "specialty", "starts_at", "status"))
        for item in context.get("appointments", [])
    ]
    if "today" in context:
        result["today"] = context["today"]
    for key in ("plans", "calendar_events", "appointments"):
        if key not in context:
            result.pop(key, None)
    return result
