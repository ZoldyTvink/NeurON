SLOT_FILLERS = {"specialty": SPECIALTIES, "drug": DRUGS, "time": TIMES, "date": DATES}


def _expand(template: str) -> list[str]:
    placeholders = [
        name for _, name, _, _ in string.Formatter().parse(template) if name
    ]
    if not placeholders:
        return [template]
    options = [SLOT_FILLERS[name] for name in placeholders]
    expanded = []
    for combo in itertools.product(*options):
        filled = template.format(**dict(zip(placeholders, combo)))
        expanded.append(filled)
    return expanded


def build_dataset(max_per_intent: int = 40) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for intent, templates in TEMPLATES.items():
        examples: set[str] = set()
        for template in templates:
            examples.update(_expand(template))
        examples_list = list(examples)
        random.shuffle(examples_list)
        for text in examples_list[:max_per_intent]:
            rows.append((text, intent))
    random.shuffle(rows)
    return rows


def write_dataset() -> Path:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    rows = build_dataset()
    with DATASET_PATH.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "intent"])
        writer.writerows(rows)
    return DATASET_PATH


if __name__ == "__main__":
    path = write_dataset()
    print(f"Wrote dataset to {path}")
